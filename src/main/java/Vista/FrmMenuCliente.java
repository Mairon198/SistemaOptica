    private void btnHistorialMedicionesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHistorialMedicionesActionPerformed
        UtilVista.ejecutar(this, () -> {
            Cliente c = usuario.getIdCliente() == null ? null : clienteService.buscarPorId(usuario.getIdCliente());
            if (c == null || c.getDni() == null) {
                throw new ValidacionException("Su cuenta no está asociada a un cliente con DNI registrado.");
            }
            new frmhistorialmedicion(c.getDni()).setVisible(true);
        });
    }//GEN-LAST:event_btnHistorialMedicionesActionPerformed

    private void btnCerrarSesionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCerrarSesionActionPerformed
        if (!UtilVista.confirmar(this, "¿Desea cerrar la sesión?")) {
            return;
        }
        for (java.awt.Window w : java.awt.Window.getWindows()) {
            if (w != this && w.isDisplayable()) {
                w.dispose();
            }
        }
        Navegador.cerrarSesion(this);
    }//GEN-LAST:event_btnCerrarSesionActionPerformed



