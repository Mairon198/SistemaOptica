    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        UtilVista.ejecutar(this, () -> {
            Cliente c = (Cliente) cboCliente.getSelectedItem();
            if (c == null) {
                throw new ValidacionException("Seleccione el cliente.");
            }
            Medicion m = new Medicion();
            m.setIdMedicion(idMedicion);
            m.setCliente(c);
            m.setOdEsfera(UtilVista.decimal(txtOdEsfera.getText(), "OD Esfera", true));
            m.setOdCilindro(UtilVista.decimal(txtOdCilindro.getText(), "OD Cilindro", false));
            m.setOdEje(enteroOpcional(txtOdEje.getText(), "OD Eje"));
            m.setOiEsfera(UtilVista.decimal(txtOiEsfera.getText(), "OI Esfera", true));
            m.setOiCilindro(UtilVista.decimal(txtOiCilindro.getText(), "OI Cilindro", false));
            m.setOiEje(enteroOpcional(txtOiEje.getText(), "OI Eje"));
            m.setAdicion(UtilVista.decimal(txtAdicion.getText(), "Adición", false));
            m.setDip(UtilVista.decimal(txtDip.getText(), "DIP", false));
            m.setObservaciones(UtilVista.opcional(txtObservaciones.getText()));

            boolean esNueva = idMedicion == 0;
            servicio.guardar(m);
            UtilVista.info(this, esNueva ? "Medición registrada." : "Medición actualizada.");
            cargarMediciones();
        });
    }//GEN-LAST:event_btnGuardarActionPerformed

