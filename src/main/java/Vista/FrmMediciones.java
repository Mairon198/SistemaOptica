    private void cargarClientes() {
        cargando = true;
        try {
            List<Cliente> clientes = servicio.listarClientes();
            cboCliente.setModel(new DefaultComboBoxModel<>(clientes.toArray(new Cliente[0])));
        } finally {
            cargando = false;
        }
        cargarMediciones();
    }

    private void cargarMediciones() {
        Cliente c = (Cliente) cboCliente.getSelectedItem();
        mediciones = c == null ? new ArrayList<>() : servicio.listarPorCliente(c.getIdCliente());
        modelo.setRowCount(0);
        for (Medicion m : mediciones) {
            modelo.addRow(new Object[]{m.getIdMedicion(),
                m.getFecha() == null ? "" : m.getFecha().format(FECHA),
                num(m.getOdEsfera()), num(m.getOdCilindro()), UtilVista.texto(m.getOdEje()),
                num(m.getOiEsfera()), num(m.getOiCilindro()), UtilVista.texto(m.getOiEje()),
                num(m.getAdicion()), num(m.getDip()), UtilVista.texto(m.getObservaciones())});
        }
        limpiar();
    }

    private void mostrarMedicion() {
        int fila = tblMediciones.getSelectedRow();
        if (fila < 0 || fila >= mediciones.size()) {
            return;
        }
        Medicion m = mediciones.get(fila);
        idMedicion = m.getIdMedicion();
        txtOdEsfera.setText(num(m.getOdEsfera()));
        txtOdCilindro.setText(num(m.getOdCilindro()));
        txtOdEje.setText(UtilVista.texto(m.getOdEje()));
        txtOiEsfera.setText(num(m.getOiEsfera()));
        txtOiCilindro.setText(num(m.getOiCilindro()));
        txtOiEje.setText(UtilVista.texto(m.getOiEje()));
        txtAdicion.setText(num(m.getAdicion()));
        txtDip.setText(num(m.getDip()));
        txtObservaciones.setText(UtilVista.texto(m.getObservaciones()));
    }

    private void limpiar() {
        idMedicion = 0;
        tblMediciones.clearSelection();
        for (JTextField t : new JTextField[]{txtOdEsfera, txtOdCilindro, txtOdEje, txtOiEsfera,
            txtOiCilindro, txtOiEje, txtAdicion, txtDip, txtObservaciones}) {
            t.setText("");
        }
        txtOdEsfera.requestFocusInWindow();
    }

    private String num(BigDecimal valor) {
        return valor == null ? "" : valor.stripTrailingZeros().toPlainString();
    }

    private Integer enteroOpcional(String valor, String campo) throws ValidacionException {
        if (valor == null || valor.trim().isEmpty()) {
            return null;
        }
        return UtilVista.entero(valor, campo);
    }

