    private void nuevaVenta() {
        venta = servicio.nuevaVenta(usuario);
        spnCantidad.setValue(1);
        refrescarDetalle();
    }

    private void cargarClientes() {
        cargando = true;
        try {
            List<Cliente> clientes = servicio.listarClientes();
            cboCliente.setModel(new DefaultComboBoxModel<>(clientes.toArray(new Cliente[0])));
        } finally {
            cargando = false;
        }
        cargarMediciones();
    }

    private void cargarMediciones() {
        cargando = true;
        try {
            Cliente c = (Cliente) cboCliente.getSelectedItem();
            List<Medicion> mediciones = c == null ? List.of() : servicio.listarMediciones(c.getIdCliente());
            cboMedicion.setModel(new DefaultComboBoxModel<>(mediciones.toArray(new Medicion[0])));
        } finally {
            cargando = false;
        }
        mostrarResumenMedicion();
    }

    private void cargarProductos() {
        cargando = true;
        try {
            String tipo = (String) cboTipoProducto.getSelectedItem();
            List<Producto> productos = servicio.listarProductosDisponibles(tipo);
            cboProducto.setModel(new DefaultComboBoxModel<>(productos.toArray(new Producto[0])));
        } finally {
            cargando = false;
        }
    }

    private void mostrarResumenMedicion() {
        Medicion m = (Medicion) cboMedicion.getSelectedItem();
        if (cboCliente.getSelectedItem() == null) {
            lblResumenMedicion.setText("No hay clientes registrados.");
        } else if (m == null) {
            lblResumenMedicion.setText("<html><font color='#b41e1e'>El cliente no tiene mediciones registradas. "
                    + "No se puede vender sin medición.</font></html>");
        } else {
            lblResumenMedicion.setText("<html><b>OD:</b> Esf " + num(m.getOdEsfera()) + " &nbsp;Cil " + num(m.getOdCilindro())
                    + " &nbsp;Eje " + eje(m.getOdEje())
                    + " &nbsp;&nbsp;|&nbsp;&nbsp; <b>OI:</b> Esf " + num(m.getOiEsfera()) + " &nbsp;Cil " + num(m.getOiCilindro())
                    + " &nbsp;Eje " + eje(m.getOiEje())
                    + " &nbsp;&nbsp;|&nbsp;&nbsp; <b>ADD:</b> " + num(m.getAdicion())
                    + " &nbsp;&nbsp;|&nbsp;&nbsp; <b>DIP:</b> " + (m.getDip() == null ? "-" : m.getDip().toPlainString() + " mm")
                    + (m.getObservaciones() == null ? "" : " &nbsp;&nbsp;|&nbsp;&nbsp; " + m.getObservaciones())
                    + "</html>");
        }
    }

    private String num(BigDecimal valor) {
        if (valor == null) {
            return "-";
        }
        return (valor.signum() > 0 ? "+" : "") + valor.setScale(2, RoundingMode.HALF_UP).toPlainString();
    }

    private String eje(Integer valor) {
        return valor == null ? "-" : valor + "°";
    }

    private void refrescarDetalle() {
        modeloDetalle.setRowCount(0);
        for (DetalleVenta d : venta.getDetalles()) {
            Producto p = d.getProducto();
            modeloDetalle.addRow(new Object[]{p.getTipo(), p.getCodigo(), p.getNombre(),
                UtilVista.dinero(d.getPrecioUnitario()), d.getCantidad(), UtilVista.dinero(d.getSubtotalLinea())});
        }
        lblSubtotal.setText(UtilVista.dinero(venta.getSubtotal()));
        lblImpuesto.setText(UtilVista.dinero(venta.getImpuesto()));
        lblTotal.setText(UtilVista.dinero(venta.getTotal()));
    }

