    private void cargarVentas() {
        ventas = servicio.listarVentas();
        modeloVentas.setRowCount(0);
        modeloDetalle.setRowCount(0);
        BigDecimal totalVendido = BigDecimal.ZERO;
        for (Venta v : ventas) {
            modeloVentas.addRow(new Object[]{v.getNumeroVenta(),
                v.getFecha() == null ? "" : v.getFecha().format(FECHA_HORA),
                v.getCliente().getNombreCompleto(), v.getVendedor().getNombreCompleto(), v.getMetodoPago(),
                UtilVista.dinero(v.getSubtotal()), UtilVista.dinero(v.getImpuesto()), UtilVista.dinero(v.getTotal())});
            totalVendido = totalVendido.add(v.getTotal());
        }
        lblResumen.setText(ventas.size() + " venta(s) - Total vendido: " + UtilVista.dinero(totalVendido));
    }

    private void cargarDetalle() {
        modeloDetalle.setRowCount(0);
        int fila = tblVentas.getSelectedRow();
        if (fila < 0 || fila >= ventas.size()) {
            return;
        }
        Venta v = servicio.buscarVenta(ventas.get(fila).getIdVenta());
        if (v == null) {
            return;
        }
        for (DetalleVenta d : v.getDetalles()) {
            Producto p = d.getProducto();
            modeloDetalle.addRow(new Object[]{p.getTipo(), p.getCodigo(), p.getNombre(),
                UtilVista.dinero(d.getPrecioUnitario()), d.getCantidad(), UtilVista.dinero(d.getSubtotalLinea())});
        }
    }

